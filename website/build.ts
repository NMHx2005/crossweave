import { createHash } from 'node:crypto'
import { existsSync, mkdirSync, readFileSync, readdirSync, rmSync, statSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { en } from './src/content/en'
import type { Content } from './src/content/types'
import { vi } from './src/content/vi'
import { imageSize } from './src/images'
import { renderDocument } from './src/layout'
import { changelogPage } from './src/pages/changelog'
import { docsPages } from './src/pages/docs'
import { downloadPage } from './src/pages/download'
import { homePage } from './src/pages/home'
import { notFoundPage } from './src/pages/notfound'
import { NOTARIZED, readManifest, refreshManifest } from './src/release'
import { escapeHtml, loadConfig, makeUrls, type Lang } from './src/site'
import { themeCss } from './src/theme'
import type { BuildOptions, BuiltPage, PageCtx } from './src/types'
import { fileURLToPath } from 'node:url'

const MARKER = '.built-by-website'

const CONTENT: Record<Lang, Content> = { en, vi }

/** `/docs/install/` is `docs/install/index.html`; `/404.html` stays itself. */
function fileFor(path: string): string {
  return path.endsWith('/') ? `${path.slice(1)}index.html` : path.slice(1)
}

function listFiles(dir: string, prefix = ''): string[] {
  return readdirSync(dir)
    .sort()
    .flatMap((name) => {
      const full = join(dir, name)
      return statSync(full).isDirectory() ? listFiles(full, `${prefix}${name}/`) : [`${prefix}${name}`]
    })
}

/** A build directory is cleaned only if this script made it: a mistyped --out can never empty a folder that holds something else. */
function prepare(out: string): void {
  if (existsSync(out)) {
    if (!existsSync(join(out, MARKER)) && readdirSync(out).length > 0) throw new Error(`${out} is not empty and was not made by this build; refusing to clear it`)
    rmSync(out, { recursive: true, force: true })
  }
  mkdirSync(out, { recursive: true })
  writeFileSync(join(out, MARKER), 'This directory is generated by website/build.ts and is cleared on every build.\n')
}

export async function build(options: BuildOptions): Promise<void> {
  const { repoRoot, out } = options
  const config = loadConfig(options.env)
  const urls = makeUrls(config)
  const manifestPath = options.manifestPath ?? join(repoRoot, 'website', 'release.json')

  if (options.refreshRelease) await refreshManifest(manifestPath, { fetcher: options.fetcher, timeoutMs: options.timeoutMs })
  const release = readManifest(manifestPath)
  const notarized = options.notarized ?? NOTARIZED
  const sizeOf = (name: string): { width: number; height: number } => imageSize(join(repoRoot, 'website', 'public', 'img', name))

  const base = { urls, release, notarized, imageSize: sizeOf }
  const ctx = (lang: Lang): PageCtx => ({ ...base, lang, content: CONTENT[lang] })

  const releasesDir = join(repoRoot, 'docs', 'releases')
  const notes = readdirSync(releasesDir)
    .filter((name) => /^v\d+\.\d+\.\d+\.md$/.test(name))
    .map((name) => ({ tag: name.replace(/\.md$/, ''), markdown: readFileSync(join(releasesDir, name), 'utf8') }))

  const pages: BuiltPage[] = [
    homePage(ctx('en')),
    homePage(ctx('vi')),
    downloadPage(ctx('en')),
    downloadPage(ctx('vi')),
    ...docsPages({
      urls,
      readme: readFileSync(join(repoRoot, 'README.md'), 'utf8'),
      concepts: readFileSync(join(repoRoot, 'website', 'src', 'content', 'concepts.md'), 'utf8'),
      cliHelp: readFileSync(join(repoRoot, 'website', 'src', 'content', 'cli-help.txt'), 'utf8'),
      release,
      imageSize: sizeOf,
    }),
    changelogPage({ urls, notes, release }),
    notFoundPage({ urls, en, vi }),
  ].sort((a, b) => (a.path < b.path ? -1 : 1))

  prepare(out)
  const write = (relative: string, data: string | Uint8Array): void => {
    const target = join(out, relative)
    mkdirSync(dirname(target), { recursive: true })
    writeFileSync(target, data)
  }

  for (const page of pages) {
    write(fileFor(page.path), renderDocument(page.meta, page.body, { content: CONTENT[page.meta.lang], urls, version: release.tag }))
  }

  write('styles.css', `${themeCss()}${readFileSync(join(repoRoot, 'website', 'src', 'styles.css'), 'utf8')}`)
  const publicDir = join(repoRoot, 'website', 'public')
  for (const file of listFiles(publicDir)) write(file, readFileSync(join(publicDir, file)))

  const sitemap = pages
    .filter((p) => p.meta.noindex !== true)
    .map((p) => `<url><loc>${escapeHtml(urls.abs(p.path))}</loc></url>`)
    .join('\n')
  write('sitemap.xml', `<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n${sitemap}\n</urlset>\n`)

  if (config.domain !== null) {
    write('CNAME', `${config.domain}\n`)
    write('robots.txt', `User-agent: *\nAllow: /\nSitemap: ${urls.abs('/sitemap.xml')}\n`)
  }
}

/** A hash of every file under a directory, keyed by relative path: two builds are the same when these maps are equal. */
export function treeHashes(dir: string): Record<string, string> {
  return Object.fromEntries(listFiles(dir).map((file) => [file, createHash('sha256').update(readFileSync(join(dir, file))).digest('hex')]))
}

if (import.meta.main) {
  const args = process.argv.slice(2)
  const out = args.includes('--out') ? args[args.indexOf('--out') + 1] : undefined
  await build({
    out: out ?? fileURLToPath(new URL('./dist', import.meta.url)),
    env: process.env,
    repoRoot: fileURLToPath(new URL('..', import.meta.url)).replace(/\/$/, ''),
    refreshRelease: args.includes('--refresh-release'),
  })
}
